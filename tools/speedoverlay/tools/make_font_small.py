# Renders the glyphs for the right box (consumption and estimated fuel) from DejaVu
# Sans into 8-bit alpha bitmaps and writes them as a C header for the player:
#   small bold digits 0-9 and ',' (index 10), regular units "l/100km" and "L",
#   and a filled jerrycan icon (drawn here, no font) as high as a digit.
import sys
from PIL import Image, ImageDraw, ImageFont
bold, regular, out = sys.argv[1], sys.argv[2], sys.argv[3]
DIG_PX, UNIT_PX = 22, 13
fb = ImageFont.truetype(bold, DIG_PX)
fr = ImageFont.truetype(regular, UNIT_PX)
asc, desc = fb.getmetrics()
H = asc + desc

def render(font, text, h):
    w = int(font.getlength(text) + 0.999) + 2
    im = Image.new("L", (w, h), 0)
    ImageDraw.Draw(im).text((1, 0), text, fill=255, font=font)
    return im

def arr(name, data):
    return "static const uint8_t %s[%d] = {%s};" % (name, len(data), ",".join(map(str, data)))

lines = ["/* Generated by tools/make_font_small.py from DejaVu Sans (see DejaVu-LICENSE.txt). */",
         "#pragma once", "#include <stdint.h>", "#define SO_SD_H %d" % H, "#define SO_SD_BASE %d" % asc]
widths, offs, data = [], [], []
for d in "0123456789,":
    im = render(fb, d, H)
    offs.append(len(data)); widths.append(im.width); data.extend(im.tobytes())
lines.append("static const uint16_t so_sd_w[11] = {%s};" % ",".join(map(str, widths)))
lines.append("static const uint32_t so_sd_off[11] = {%s};" % ",".join(map(str, offs)))
lines.append(arr("so_sd_px", data))

ua, ud = fr.getmetrics()
for name, text in (("SO_SU1", "l/100km"), ("SO_SU2", "L")):
    u = render(fr, text, ua + ud)
    lines.append("#define %s_W %d" % (name, u.width))
    lines.append("#define %s_H %d" % (name, u.height))
    lines.append(arr(name.lower() + "_px", list(u.tobytes())))
lines.append("#define SO_SU_BASE %d" % ua)

# Jerrycan: body with a cut corner top left, handle hole top right, spout top left.
# Drawn at 8x on a 130 x 135 design grid, then scaled to the digit cap height.
S = 8
big = Image.new("L", (136 * S, 136 * S), 0)
g = ImageDraw.Draw(big)
def P(x, y):
    return (x * S, y * S)
def quad(p0, p1, p2, n=12):
    return [((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0],
             (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1]) for t in [i / n for i in range(n + 1)]]
body = [(40, 30), (95, 30)] + quad((95, 30), (105, 30), (112, 37)) + [(118, 43), (118, 120)] \
    + quad((118, 120), (118, 130), (108, 130)) + [(22, 130)] + quad((22, 130), (12, 130), (12, 120)) + [(12, 58)]
g.polygon([P(x, y) for x, y in body], fill=255)
g.rounded_rectangle([P(66, 40), P(100, 58)], radius=9 * S, fill=0)
spout = Image.new("L", big.size, 0)
ImageDraw.Draw(spout).rounded_rectangle([P(8, 10), P(22, 48)], radius=5 * S, fill=255)
spout = spout.rotate(-45, resample=Image.BICUBIC, center=P(15, 29))
big = Image.composite(spout, big, spout)
bbox = big.getbbox()
big = big.crop(bbox)
cap = fb.getbbox("0")[3] - fb.getbbox("0")[1]
ih = cap + 1
iw = max(1, round(big.width * ih / big.height))
icon = big.resize((iw, ih), Image.LANCZOS)
lines.append("#define SO_ICON_W %d" % iw)
lines.append("#define SO_ICON_H %d" % ih)
lines.append(arr("so_icon_px", list(icon.tobytes())))
open(out, "w", newline="\n").write("\n".join(lines) + "\n")
print("small digit height", H, "base", asc, "widths", widths, "cap", cap, "icon", (iw, ih))
