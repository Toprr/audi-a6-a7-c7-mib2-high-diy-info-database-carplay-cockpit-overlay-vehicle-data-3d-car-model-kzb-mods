# Renders the digits 0-9 (bold) and the word "km/h" (regular) from DejaVu Sans
# into 8-bit alpha bitmaps and writes them as a C header for the player.
import sys
from PIL import Image, ImageDraw, ImageFont
bold, regular, out = sys.argv[1], sys.argv[2], sys.argv[3]
DIG_PX, UNIT_PX = 40, 17
fb = ImageFont.truetype(bold, DIG_PX)
fr = ImageFont.truetype(regular, UNIT_PX)
asc, desc = fb.getmetrics()
H = asc + desc
def render(font, text, h):
    w = int(font.getlength(text) + 0.999) + 2
    im = Image.new("L", (w, h), 0)
    ImageDraw.Draw(im).text((1, 0), text, fill=255, font=font)
    return im
lines = ["/* Generated by tools/make_font.py from DejaVu Sans (see DejaVu-LICENSE.txt). */",
         "#pragma once", "#include <stdint.h>", "#define SO_DIG_H %d" % H]
widths, offs, data = [], [], []
for d in "0123456789":
    im = render(fb, d, H)
    offs.append(len(data)); widths.append(im.width); data.extend(im.tobytes())
lines.append("static const uint16_t so_dig_w[10] = {%s};" % ",".join(map(str, widths)))
lines.append("static const uint32_t so_dig_off[10] = {%s};" % ",".join(map(str, offs)))
lines.append("static const uint8_t so_dig_px[%d] = {%s};" % (len(data), ",".join(map(str, data))))
ua, ud = fr.getmetrics()
u = render(fr, "km/h", ua + ud)
lines.append("#define SO_UNIT_W %d" % u.width)
lines.append("#define SO_UNIT_H %d" % u.height)
lines.append("#define SO_UNIT_BASE %d" % ua)
lines.append("#define SO_DIG_BASE %d" % asc)
lines.append("static const uint8_t so_unit_px[%d] = {%s};" % (u.width * u.height, ",".join(map(str, u.tobytes()))))
open(out, "w", newline="\n").write("\n".join(lines) + "\n")
print("digit height", H, "widths", widths, "unit", u.size)
